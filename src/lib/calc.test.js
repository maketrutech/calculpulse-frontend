import test from 'node:test'
import assert from 'node:assert/strict'
import * as c from './calc.js'
import { fmt, parseNum, money } from './num.js'
import { convert } from './units.js'
import { numberToWords, euroToWords, decimalToWords } from './words.fr.js'

const near = (a, b, eps = 1e-9) => assert.ok(Math.abs(a - b) < eps, `${a} ≠ ${b}`)

test('parseNum accepte la virgule et les espaces', () => {
  assert.equal(parseNum('12,5'), 12.5)
  assert.equal(parseNum('1 234,56'), 1234.56)
  assert.equal(parseNum('1\u202f234'), 1234)
  assert.equal(parseNum('1.234,5'), 1234.5)
  assert.equal(parseNum('-3'), -3)
  assert.equal(parseNum('20 %'), 20)
  assert.ok(Number.isNaN(parseNum('abc')))
  assert.ok(Number.isNaN(parseNum('')))
  assert.ok(Number.isNaN(parseNum('1,2,3')))
})

test('fmt au format français', () => {
  assert.equal(fmt(1234.5), '1\u00a0234,5')
  assert.equal(fmt(0.1 + 0.2), '0,3')
  assert.equal(fmt(-2.005, 2), '−2,01')
  assert.equal(fmt(1.005, 2), '1,01')
  assert.equal(money(12), '12,00\u00a0€')
  assert.equal(fmt(-0.0001), '0')
})

test('pourcentages', () => {
  assert.equal(c.percentOf(20, 150), 30)
  assert.equal(c.whatPercent(30, 120), 25)
  assert.equal(c.evolutionRate(80, 100), 25)
  assert.equal(c.evolutionRate(100, 80), -20)
  near(c.applyRate(200, 15), 230)
  near(c.beforeRate(230, 15), 200)
  near(c.reciprocalRate(25), -20)
  near(c.chainRates([10, 10]), 21)
  near(c.chainRates([20, -20]), -4)
})

test('TVA', () => {
  const a = c.tva(100, 20, 'ht')
  near(a.ttc, 120); near(a.tva, 20)
  const b = c.tva(120, 20, 'ttc')
  near(b.ht, 100); near(b.tva, 20)
  near(c.tva(100, 5.5).ttc, 105.5)
  near(c.tva(110, 10, 'ttc').ht, 100)
})

test('produit en croix et moyennes', () => {
  assert.equal(c.crossProduct(4, 6, 10), 15)
  assert.equal(c.mean([10, 12, 14]), 12)
  near(c.weightedMean([12, 15, 9], [2, 3, 1]), 13)
  assert.equal(c.median([5, 1, 3]), 3)
  assert.equal(c.median([4, 1, 3, 2]), 2.5)
  near(c.stdDev([2, 4, 4, 4, 5, 5, 7, 9]), 2)
  near(c.variance([1, 2, 3, 4], true), 1.6666666666666667)
  assert.equal(c.rescale(15, 30), 10)
  assert.equal(c.rescale(14, 20, 10), 7)
})

test('chiffres romains', () => {
  assert.equal(c.toRoman(1994), 'MCMXCIV')
  assert.equal(c.toRoman(2026), 'MMXXVI')
  assert.equal(c.toRoman(3999), 'MMMCMXCIX')
  assert.equal(c.toRoman(0), null)
  assert.equal(c.fromRoman('mcmxciv'), 1994)
  assert.equal(c.fromRoman('XIV'), 14)
  assert.equal(c.fromRoman('IIII'), null)
  assert.equal(c.fromRoman('IC'), null)
  for (let n = 1; n <= 3999; n += 1) assert.equal(c.fromRoman(c.toRoman(n)), n)
})

test('remise, intérêts, marge, IMC, surfaces', () => {
  assert.deepEqual(c.discount(80, 25), { final: 60, saving: 20 })
  assert.equal(c.simpleInterest(1000, 3, 2), 60)
  near(c.compound({ capital: 1000, rate: 5, years: 2 }).final, 1102.5)
  near(c.compound({ capital: 1000, rate: 12, years: 1, freq: 'mensuelle' }).final, 1000 * 1.01 ** 12)
  near(c.compound({ capital: 0, rate: 0, years: 1, monthly: 100 }).final, 1200)
  const m = c.margin(50, 80)
  near(m.margin, 30); near(m.markupRate, 60); near(m.marginRate, 37.5); near(m.coef, 1.6)
  near(c.priceFromMarginRate(60, 25), 80)
  near(c.priceFromMarkup(60, 25), 75)
  near(c.bmi(70, 175), 22.857142857142858)
  assert.equal(c.bmiClass(22.9), 'Corpulence normale')
  assert.equal(c.bmiClass(30), 'Obésité modérée')
  assert.equal(c.area('rectangle', 4, 3), 12)
  assert.equal(c.area('trapeze', 4, 6, 2), 10)
  near(c.area('cercle', 1), Math.PI)
  assert.deepEqual(c.simplifySqrt(72), { outside: 6, inside: 2 })
})

test('conversions', () => {
  near(convert(1, 'pouce', 'cm'), 2.54)
  near(convert(55, 'pouce', 'cm'), 139.7)
  near(convert(1, 'mile', 'km'), 1.609344)
  near(convert(100, 'km', 'mile'), 62.13711922373339)
  near(convert(1, 'livre', 'kg'), 0.45359237)
  near(convert(212, 'fahrenheit', 'celsius'), 100)
  near(convert(-40, 'celsius', 'fahrenheit'), -40)
  near(convert(37, 'celsius', 'fahrenheit'), 98.6)
  near(convert(1, 'gallon', 'litre'), 3.785411784)
  near(convert(1, 'noeud', 'kmh'), 1.852)
  near(convert(60, 'mph', 'kmh'), 96.56064)
  near(convert(1, 'acre', 'm2'), 4046.8564224)
  near(convert(6, 'pied', 'cm'), 182.88)
  assert.ok(Number.isNaN(convert(1, 'kg', 'cm')))
})

test('nombres en lettres', () => {
  const w = (n, r) => numberToWords(n, { rectified: r })
  assert.equal(w(0), 'zéro')
  assert.equal(w(21), 'vingt et un')
  assert.equal(w(71), 'soixante et onze')
  assert.equal(w(80), 'quatre-vingts')
  assert.equal(w(81), 'quatre-vingt-un')
  assert.equal(w(91), 'quatre-vingt-onze')
  assert.equal(w(99), 'quatre-vingt-dix-neuf')
  assert.equal(w(200), 'deux cents')
  assert.equal(w(201), 'deux cent un')
  assert.equal(w(1000), 'mille')
  assert.equal(w(80000), 'quatre-vingt mille')
  assert.equal(w(200000), 'deux cent mille')
  assert.equal(w(1980), 'mille neuf cent quatre-vingts')
  assert.equal(w(2000000), 'deux millions')
  assert.equal(w(1234567), 'un million deux cent trente-quatre mille cinq cent soixante-sept')
  assert.equal(w(1021, true), 'mille-vingt-et-un')
  assert.equal(w(300000000), 'trois cents millions')
  assert.equal(euroToWords(1250.5), 'mille deux cent cinquante euros et cinquante centimes')
  assert.equal(euroToWords(1), 'un euro')
  assert.equal(euroToWords(1000000), 'un million d’euros')
  assert.equal(decimalToWords('3,05'), 'trois virgule zéro cinq')
})
